// 将元组数组映射为带 id/sort 的 CityPoint 列表，id 取负数避免与后端冲突
export const nationwideCities: CityPoint[] = tuples.map((t, i) => ({
  // 负 id，避免与后端自增主键冲突
  id: -(i + 1),
  // 城市中文名
  name: t[0],
  // 城市全拼
  pinyin: t[1],
  // 城市首字母
  initial: t[2],
  // 排序序号按数组顺序
  sort: i + 1,
  // 城市中心纬度
  lat: t[3],
  // 城市中心经度
  lng: t[4],
}))

// 按关键字搜索全国城市：支持中文名、全拼、首字母匹配，返回最多 50 条
export function searchNationwide(keyword: string): CityPoint[] {
  // 去除首尾空白并转小写，便于拼音匹配
  const k = keyword.trim().toLowerCase()
  // 空关键字返回前 50 条热门城市
  if (!k) return nationwideCities.slice(0, 50)
  // 按名称/全拼/首字母过滤，最多返回 50 条
  return nationwideCities
    .filter((c) => c.name.includes(k) || c.pinyin.includes(k) || c.initial.toLowerCase() === k)
    .slice(0, 50)
}
